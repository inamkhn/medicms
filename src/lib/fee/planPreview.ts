// ============================================
// MediCMS Desktop - Fee engine: the student's plan, term by term (§13.7)
//
// One call turns a computed template and a set of concession records into the
// numbers the admission screen and the profile both show: the opening term after
// concessions, and every later billed term (the "view all terms" table). The
// engine stays the only place money is worked out - this module just asks it
// once per term so two screens cannot disagree.
// ============================================

import { applyConcessions, type ApplyConcessionsResult, type ConcessionLine } from './concessions.ts';
import type { ConcessionRecord, TermFee, TermScope } from './types.ts';

/** One row of the §13.7 preview: what a term costs before and after the records. */
export interface PreviewTerm {
  term: number;
  template: number;
  concession: number;
  net: number;
}

export interface PlanPreview {
  terms: PreviewTerm[];
  /** The term the student joins: the charge that posts at admission (§5.4). */
  opening: {
    term: number;
    template: number;
    concession: number;
    net: number;
    lines: ConcessionLine[];
    warnings: string[];
    applied: ApplyConcessionsResult['applied'];
  };
}

/**
 * §13.7 - every billed term from `startingTerm` to the end, with the live records
 * applied. `termFees` is the engine's own output (`computeTemplateTermFees`), so a
 * record is priced exactly the same here as it will be when that term is billed.
 */
export function planPreview(
  termFees: readonly TermFee[],
  records: readonly ConcessionRecord[],
  startingTerm: number,
): PlanPreview {
  const from = Math.max(1, Math.trunc(startingTerm) || 1);
  const rows = termFees.filter((t) => t.term >= from).slice().sort((a, b) => a.term - b.term);
  const terms: PreviewTerm[] = [];
  let opening: PlanPreview['opening'] | null = null;
  for (const row of rows) {
    const lines = row.lines.map((l) => ({ componentId: l.componentId, name: l.name, amount: l.amount }));
    const result = applyConcessions(lines, records, row.term);
    terms.push({ term: row.term, template: result.templateTotal, concession: result.totalConcession, net: result.netTotal });
    if (!opening) {
      opening = {
        term: row.term,
        template: result.templateTotal,
        concession: result.totalConcession,
        net: result.netTotal,
        lines: result.lines,
        warnings: result.warnings,
        applied: result.applied,
      };
    }
  }
  return {
    terms,
    opening: opening ?? { term: from, template: 0, concession: 0, net: 0, lines: [], warnings: [], applied: [] },
  };
}

/**
 * §13.4 - the scope in words, shared by the admission editor and the profile's
 * fee plan card so one record reads the same wherever it is shown.
 */
export function scopeLabel(scope: TermScope): string {
  switch (scope.mode) {
    case 'termOnly':
      return `Term ${scope.term} only`;
    case 'remainingTerms':
      return `All terms from ${scope.fromTerm}`;
    case 'specificTerms':
      return `Terms ${scope.from}-${scope.to}`;
    default:
      return '';
  }
}

/**
 * §13.3 - the reduction in the words of the screen ("20% off", "set to ..."), with
 * the money formatter injected so this module stays free of app imports.
 */
export function concessionValueLabel(record: ConcessionRecord, money: (n: number) => string): string {
  switch (record.kind) {
    case 'waive':
      return 'Waived';
    case 'fixed':
      return `${money(record.value)} off`;
    case 'percent':
      return `${record.value}% off`;
    case 'setAmount':
      return `Set to ${money(record.value)}`;
    default:
      return '';
  }
}

/**
 * §26.1 - two plans say the same thing when their records mean the same thing: the
 * ids are regenerated by the editor, so they are not part of the meaning, and a
 * re-added identical record is not a change.
 */
export function planSignature(records: readonly ConcessionRecord[]): string {
  return JSON.stringify(records.map((record) => {
    const t = record.target;
    const s = record.scope;
    return [
      t.kind === 'plan' ? 'plan' : `c:${t.componentId}`,
      record.kind,
      record.value,
      s.mode,
      s.mode === 'termOnly' ? s.term : '',
      s.mode === 'remainingTerms' ? s.fromTerm : '',
      s.mode === 'specificTerms' ? `${s.from}-${s.to}` : '',
      record.reasonCategory,
      record.note.trim(),
    ];
  }));
}
